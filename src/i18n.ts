export type AppLanguage = "en" | "ru" | "uk";

export const LANGUAGE_STORAGE_KEY = "lopster-language";

export const languageNames: Record<AppLanguage, string> = {
  en: "English",
  ru: "Русский",
  uk: "Українська",
};

export function isAppLanguage(value: unknown): value is AppLanguage {
  return value === "en" || value === "ru" || value === "uk";
}

export function getStoredLanguage(): AppLanguage {
  try {
    const raw = window.localStorage.getItem(LANGUAGE_STORAGE_KEY);
    if (isAppLanguage(raw)) return raw;
  } catch {
    /* ignore */
  }
  return "en";
}

export function setStoredLanguage(lang: AppLanguage): void {
  try {
    window.localStorage.setItem(LANGUAGE_STORAGE_KEY, lang);
  } catch {
    /* ignore */
  }
  if (typeof document !== "undefined") {
    document.documentElement.lang = lang;
  }
}

export function applyLanguage(lang: AppLanguage): AppLanguage {
  const next = isAppLanguage(lang) ? lang : "en";
  setStoredLanguage(next);
  return next;
}

export function formatTemplate(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, key: string) =>
    vars[key] != null ? String(vars[key]) : `{${key}}`
  );
}

