/**
 * Per-project file backups at <project>/.backup
 *
 * On every edit_file / create_file (existing file overwrite path), a copy of the
 * previous content is stored so the agent can restore if it deletes/corrupts a file.
 *
 * Layout:
 *   .backup/
 *     index.json          — catalog of versions
 *     files/
 *       <safe-rel-path>/
 *         <timestamp>_<id>.bak
 *
 * Each project root has its own .backup (nothing global).
 */

const fs = require("fs");
const path = require("path");
const crypto = require("crypto");
const fileDiff = require("./fileDiff.cjs");

const BACKUP_DIR = ".backup";
const FILES_SUBDIR = "files";
const INDEX_FILE = "index.json";

const MAX_VERSIONS_PER_FILE = 20;
const MAX_FILE_BYTES = 5 * 1024 * 1024;
const MAX_TOTAL_VERSIONS = 800;
const MAX_BACKUP_DIR_BYTES = 80 * 1024 * 1024;
const MAX_AGE_MS = 7 * 24 * 60 * 60 * 1000;
const DEFAULT_LIST_LIMIT = 40;

function getBackupRoot(projectRoot) {
  if (!projectRoot || typeof projectRoot !== "string") return null;
  return path.join(projectRoot, BACKUP_DIR);
}

function getFilesDir(projectRoot) {
  const root = getBackupRoot(projectRoot);
  return root ? path.join(root, FILES_SUBDIR) : null;
}

function getIndexPath(projectRoot) {
  const root = getBackupRoot(projectRoot);
  return root ? path.join(root, INDEX_FILE) : null;
}

function toRelative(projectRoot, filePath) {
  const rel = path.relative(projectRoot, filePath);
  if (!rel || rel.startsWith("..") || path.isAbsolute(rel)) return null;
  return rel.split(path.sep).join("/");
}

function toAbsolute(projectRoot, relativePath) {
  return path.join(projectRoot, ...String(relativePath).split("/"));
}

/** Safe directory name for a relative path (no path separators). */
function safeRelDir(relativePath) {
  return String(relativePath)
    .replace(/\\/g, "/")
    .replace(/^\.?\//, "")
    .replace(/\.\./g, "_")
    .replace(/[<>:"|?*\x00-\x1f]/g, "_")
    .replace(/\//g, "__");
}

async function ensureBackupDirs(projectRoot) {
  const root = getBackupRoot(projectRoot);
  const files = getFilesDir(projectRoot);
  if (!root || !files) return null;
  await fs.promises.mkdir(files, { recursive: true });
  // Best-effort hide on Windows + ignore hint
  try {
    await fs.promises.writeFile(
      path.join(root, ".gitignore"),
      "# Auto-generated by ComposeVC — per-file restore backups\n*\n!.gitignore\n",
      { flag: "wx" }
    );
  } catch {
    /* exists */
  }
  return root;
}

async function readIndex(projectRoot) {
  const indexPath = getIndexPath(projectRoot);
  if (!indexPath) return { versions: [] };
  try {
    const raw = await fs.promises.readFile(indexPath, "utf8");
    const data = JSON.parse(raw);
    return {
      versions: Array.isArray(data.versions) ? data.versions : [],
    };
  } catch {
    return { versions: [] };
  }
}

async function writeIndex(projectRoot, index) {
  await ensureBackupDirs(projectRoot);
  const indexPath = getIndexPath(projectRoot);
  await fs.promises.writeFile(indexPath, JSON.stringify(index, null, 2), "utf8");
}

/** Recursive byte size of a directory (best-effort). */
async function getDirSizeBytes(dirPath) {
  if (!dirPath) return 0;
  let total = 0;
  async function walk(current) {
    let entries;
    try {
      entries = await fs.promises.readdir(current, { withFileTypes: true });
    } catch {
      return;
    }
    for (const entry of entries) {
      const full = path.join(current, entry.name);
      try {
        if (entry.isDirectory()) {
          await walk(full);
        } else if (entry.isFile()) {
          const st = await fs.promises.stat(full);
          total += st.size || 0;
        }
      } catch {
        /* skip unreadable */
      }
    }
  }
  await walk(dirPath);
  return total;
}

/**
 * Fully wipe project .backup (files + index). Keeps/recreates .gitignore.
 * Used when folder size exceeds MAX_BACKUP_DIR_BYTES.
 */
async function clearAllBackups(projectRoot) {
  const root = getBackupRoot(projectRoot);
  const filesDir = getFilesDir(projectRoot);
  if (!root || !filesDir) return { cleared: false, bytes: 0 };

  let bytesBefore = 0;
  try {
    bytesBefore = await getDirSizeBytes(root);
  } catch {
    /* */
  }

  try {
    await fs.promises.rm(filesDir, { recursive: true, force: true });
  } catch {
    /* */
  }
  try {
    const indexPath = getIndexPath(projectRoot);
    if (indexPath) await fs.promises.unlink(indexPath);
  } catch {
    /* */
  }

  await ensureBackupDirs(projectRoot);
  await writeIndex(projectRoot, { versions: [] });
  return { cleared: true, bytesBefore };
}

/**
 * If .backup is larger than MAX_BACKUP_DIR_BYTES, delete everything in it.
 * @returns {{ cleared: boolean, bytes: number, bytesBefore?: number }}
 */
async function enforceBackupSizeLimit(projectRoot) {
  const root = getBackupRoot(projectRoot);
  if (!root) return { cleared: false, bytes: 0 };

  let exists = false;
  try {
    await fs.promises.access(root);
    exists = true;
  } catch {
    return { cleared: false, bytes: 0 };
  }
  if (!exists) return { cleared: false, bytes: 0 };

  let bytes = 0;
  try {
    bytes = await getDirSizeBytes(root);
  } catch {
    return { cleared: false, bytes: 0 };
  }
  if (bytes <= MAX_BACKUP_DIR_BYTES) {
    return { cleared: false, bytes };
  }

  const wiped = await clearAllBackups(projectRoot);
  console.warn(
    `[fileBackup] .backup exceeded ${Math.round(MAX_BACKUP_DIR_BYTES / (1024 * 1024))}MB ` +
      `(was ~${Math.round((wiped.bytesBefore || bytes) / (1024 * 1024))}MB) — fully cleared for ${projectRoot}`
  );
  return {
    cleared: true,
    bytes: 0,
    bytesBefore: wiped.bytesBefore || bytes,
  };
}

/**
 * Snapshot current file content into .backup before mutation.
 * No-op if file missing (create_file of brand-new path) or too large / outside project.
 *
 * @param {string} projectRoot
 * @param {string} filePath absolute
 * @param {{ reason?: string }} [opts]
 * @returns {Promise<object|null>} version entry or null
 */
async function backupFileBeforeWrite(projectRoot, filePath, opts = {}) {
  if (!projectRoot || !filePath) return null;
  const abs = path.resolve(filePath);
  const rel = toRelative(path.resolve(projectRoot), abs);
  if (!rel) return null;
  // Never backup inside .backup itself
  if (rel === BACKUP_DIR || rel.startsWith(BACKUP_DIR + "/")) return null;

  let stat;
  try {
    stat = await fs.promises.stat(abs);
  } catch {
    return null; // new file — nothing to backup
  }
  if (!stat.isFile() || stat.size > MAX_FILE_BYTES) return null;

  let content;
  try {
    content = await fs.promises.readFile(abs);
  } catch {
    return null;
  }

  await ensureBackupDirs(projectRoot);
  // Auto full-clean if folder already bloated (>150MB) before adding more.
  try {
    await enforceBackupSizeLimit(projectRoot);
  } catch (err) {
    console.warn("fileBackup size enforce (pre) failed:", err?.message || err);
  }

  const id = crypto.randomBytes(6).toString("hex");
  const ts = Date.now();
  const dirName = safeRelDir(rel);
  const versionDir = path.join(getFilesDir(projectRoot), dirName);
  await fs.promises.mkdir(versionDir, { recursive: true });
  const storeName = `${ts}_${id}.bak`;
  const storePath = path.join(versionDir, storeName);
  await fs.promises.writeFile(storePath, content);

  const entry = {
    id: `${ts}_${id}`,
    path: rel,
    createdAt: ts,
    bytes: content.length,
    reason: opts.reason || "edit",
    // Relative to project root (includes .backup/) so restore/unlink resolve correctly.
    store: path
      .join(BACKUP_DIR, FILES_SUBDIR, dirName, storeName)
      .split(path.sep)
      .join("/"),
  };

  const index = await readIndex(projectRoot);
  index.versions.unshift(entry);

  const dropIds = new Set();
  if (MAX_AGE_MS > 0) {
    const cutoff = Date.now() - MAX_AGE_MS;
    for (const v of index.versions) {
      if (v.id !== entry.id && (v.createdAt || 0) < cutoff) {
        dropIds.add(v.id);
      }
    }
  }

  const forFile = index.versions.filter((v) => v.path === rel && !dropIds.has(v.id));
  if (forFile.length > MAX_VERSIONS_PER_FILE) {
    for (const d of forFile.slice(MAX_VERSIONS_PER_FILE)) {
      dropIds.add(d.id);
    }
  }

  let kept = index.versions.filter((v) => !dropIds.has(v.id));
  if (kept.length > MAX_TOTAL_VERSIONS) {
    for (const d of kept.slice(MAX_TOTAL_VERSIONS)) {
      dropIds.add(d.id);
    }
    kept = kept.filter((v) => !dropIds.has(v.id));
  }

  if (dropIds.size > 0) {
    for (const v of index.versions) {
      if (!dropIds.has(v.id)) continue;
      try {
        await fs.promises.unlink(path.join(projectRoot, v.store));
      } catch {
        /* */
      }
    }
    index.versions = kept;
  }

  await writeIndex(projectRoot, index);
  try {
    const sizeCheck = await enforceBackupSizeLimit(projectRoot);
    if (sizeCheck.cleared) {
      await ensureBackupDirs(projectRoot);
      const versionDir2 = path.join(getFilesDir(projectRoot), dirName);
      await fs.promises.mkdir(versionDir2, { recursive: true });
      await fs.promises.writeFile(path.join(versionDir2, storeName), content);
      await writeIndex(projectRoot, { versions: [entry] });
      entry.backupDirCleared = true;
      entry.backupDirBytesBefore = sizeCheck.bytesBefore;
    }
  } catch (err) {
    console.warn("fileBackup size enforce (post) failed:", err?.message || err);
  }

  return entry;
}

function resolveRelPath(projectRoot, filePath) {
  if (!filePath) return null;
  const abs = path.isAbsolute(filePath)
    ? path.resolve(filePath)
    : path.resolve(projectRoot, filePath);
  return (
    toRelative(path.resolve(projectRoot), abs) ||
    String(filePath).split(path.sep).join("/")
  );
}

function findVersion(index, { id = null, path: filePath = null, projectRoot = null } = {}) {
  if (id) {
    const entry = index.versions.find((v) => v.id === id || String(v.id).startsWith(String(id)));
    return entry || null;
  }
  if (filePath && projectRoot) {
    const rel = resolveRelPath(projectRoot, filePath);
    return index.versions.find((v) => v.path === rel || v.path.endsWith(rel)) || null;
  }
  return null;
}

async function readBackupBlob(projectRoot, entry) {
  if (!entry || !entry.store) throw new Error("Backup entry has no store path");
  const storeAbs = path.join(projectRoot, entry.store);
  try {
    return await fs.promises.readFile(storeAbs);
  } catch {
    throw new Error(`Backup blob missing on disk: ${entry.store}`);
  }
}

async function listBackups(projectRoot, filePath = null, opts = {}) {
  if (!projectRoot) return [];
  const index = await readIndex(projectRoot);
  let versions = index.versions;
  if (filePath) {
    const rel = resolveRelPath(projectRoot, filePath);
    versions = versions.filter((v) => v.path === rel || v.path.endsWith(rel));
  }
  const withStats = Boolean(opts.withStats);
  const out = [];
  for (const v of versions) {
    const item = {
      id: v.id,
      path: v.path,
      createdAt: v.createdAt,
      createdAtIso: new Date(v.createdAt).toISOString(),
      bytes: v.bytes,
      reason: v.reason || "edit",
      ageMs: Date.now() - (v.createdAt || 0),
    };
    if (withStats) {
      try {
        const targetAbs = toAbsolute(projectRoot, v.path);
        let current = null;
        try {
          current = await fs.promises.readFile(targetAbs, "utf8");
        } catch {
          current = null;
        }
        const buf = await readBackupBlob(projectRoot, v);
        const oldText = buf.toString("utf8");
        if (current == null) {
          item.exists = false;
          item.stats = { changed: true, added: 0, removed: fileDiff.splitLines(oldText).length, equal: 0 };
          item.summary = "file missing on disk (restore would recreate)";
        } else {
          item.exists = true;
          item.stats = fileDiff.quickChanged(oldText, current);
          const s = item.stats;
          item.summary = s.changed
            ? `+${s.added}/-${s.removed} vs current`
            : "identical to current";
        }
      } catch {
        item.stats = null;
        item.summary = "blob unreadable";
      }
    }
    out.push(item);
  }
  return out;
}

async function getBackupStatus(projectRoot) {
  if (!projectRoot) {
    return { ok: false, error: "no project root" };
  }
  const root = getBackupRoot(projectRoot);
  const index = await readIndex(projectRoot);
  let bytes = 0;
  try {
    bytes = await getDirSizeBytes(root);
  } catch {
    bytes = 0;
  }
  const byPath = new Map();
  for (const v of index.versions) {
    byPath.set(v.path, (byPath.get(v.path) || 0) + 1);
  }
  const topFiles = [...byPath.entries()]
    .sort((a, b) => b[1] - a[1])
    .slice(0, 15)
    .map(([p, count]) => ({ path: p, versions: count }));
  return {
    ok: true,
    projectRoot,
    backupDir: root,
    versionCount: index.versions.length,
    uniqueFiles: byPath.size,
    bytes,
    bytesHuman: `${Math.round((bytes / (1024 * 1024)) * 10) / 10} MB`,
    limits: {
      maxVersionsPerFile: MAX_VERSIONS_PER_FILE,
      maxTotalVersions: MAX_TOTAL_VERSIONS,
      maxBackupDirBytes: MAX_BACKUP_DIR_BYTES,
      maxAgeMs: MAX_AGE_MS,
    },
    topFiles,
    newest: index.versions[0]
      ? {
          id: index.versions[0].id,
          path: index.versions[0].path,
          createdAt: index.versions[0].createdAt,
        }
      : null,
  };
}

async function diffBackup(projectRoot, { id = null, path: filePath = null, context = 3 } = {}) {
  if (!projectRoot) throw new Error("diff requires an open project root");
  const index = await readIndex(projectRoot);
  const entry = findVersion(index, { id, path: filePath, projectRoot });
  if (!entry) {
    throw new Error(
      id
        ? `Backup id not found: ${id}`
        : `No backup found for path: ${filePath || "(none)"}`
    );
  }

  const buf = await readBackupBlob(projectRoot, entry);
  const oldText = buf.toString("utf8");
  const targetAbs = toAbsolute(projectRoot, entry.path);
  let newText = "";
  let currentExists = true;
  try {
    newText = await fs.promises.readFile(targetAbs, "utf8");
  } catch {
    currentExists = false;
    newText = "";
  }

  const result = fileDiff.diffTexts(oldText, newText, {
    oldPath: `${entry.path}@${entry.id}`,
    newPath: currentExists ? entry.path : `${entry.path} (missing)`,
    context: Math.min(12, Math.max(0, Number(context) || 3)),
  });

  return {
    ok: true,
    id: entry.id,
    path: entry.path,
    reason: entry.reason || "edit",
    createdAt: entry.createdAt,
    createdAtIso: new Date(entry.createdAt).toISOString(),
    currentExists,
    oldBytes: buf.length,
    newBytes: Buffer.byteLength(newText, "utf8"),
    stats: result.stats,
    oldLines: result.oldLines,
    newLines: result.newLines,
    hunkCount: result.hunkCount,
    truncated: result.truncated,
    unified: result.unified,
    tip: result.stats?.changed
      ? "Call restore_backup action=restore id=<id> to roll back the whole file to this snapshot (atomic, no partial line rewrite)."
      : "Backup matches current file — nothing to restore.",
  };
}

async function cleanupBackups(projectRoot, opts = {}) {
  if (!projectRoot) throw new Error("cleanup requires an open project root");
  const dryRun = Boolean(opts.dryRun);
  const keepPerFile = Math.max(
    1,
    Number(opts.keepPerFile) || MAX_VERSIONS_PER_FILE
  );
  const maxTotal = Math.max(1, Number(opts.maxTotal) || MAX_TOTAL_VERSIONS);
  const maxAgeMs = Number.isFinite(Number(opts.maxAgeMs))
    ? Number(opts.maxAgeMs)
    : opts.maxAgeDays != null
      ? Math.max(0, Number(opts.maxAgeDays)) * 24 * 60 * 60 * 1000
      : MAX_AGE_MS;
  const forceClear = Boolean(opts.clearAll || opts.wipe);

  if (forceClear) {
    if (dryRun) {
      const status = await getBackupStatus(projectRoot);
      return {
        ok: true,
        dryRun: true,
        action: "clearAll",
        wouldRemove: status.versionCount,
        bytes: status.bytes,
      };
    }
    const wiped = await clearAllBackups(projectRoot);
    return {
      ok: true,
      action: "clearAll",
      removed: "all",
      bytesBefore: wiped.bytesBefore || 0,
    };
  }

  const index = await readIndex(projectRoot);
  const now = Date.now();
  const dropIds = new Set();
  const reasons = [];

  if (maxAgeMs > 0) {
    for (const v of index.versions) {
      if (now - (v.createdAt || 0) > maxAgeMs) {
        dropIds.add(v.id);
        reasons.push({ id: v.id, path: v.path, reason: "age" });
      }
    }
  }

  const byPath = new Map();
  for (const v of index.versions) {
    if (dropIds.has(v.id)) continue;
    if (!byPath.has(v.path)) byPath.set(v.path, []);
    byPath.get(v.path).push(v);
  }
  for (const [, list] of byPath) {
    list.sort((a, b) => (b.createdAt || 0) - (a.createdAt || 0));
    if (list.length > keepPerFile) {
      for (const d of list.slice(keepPerFile)) {
        dropIds.add(d.id);
        reasons.push({ id: d.id, path: d.path, reason: "per-file-cap" });
      }
    }
  }

  let kept = index.versions.filter((v) => !dropIds.has(v.id));
  kept.sort((a, b) => (b.createdAt || 0) - (a.createdAt || 0));
  if (kept.length > maxTotal) {
    for (const d of kept.slice(maxTotal)) {
      dropIds.add(d.id);
      reasons.push({ id: d.id, path: d.path, reason: "global-cap" });
    }
    kept = kept.slice(0, maxTotal);
  }

  let freedBytes = 0;
  if (!dryRun) {
    for (const v of index.versions) {
      if (!dropIds.has(v.id)) continue;
      try {
        const storeAbs = path.join(projectRoot, v.store);
        const st = await fs.promises.stat(storeAbs);
        freedBytes += st.size || 0;
        await fs.promises.unlink(storeAbs);
      } catch {
        /* */
      }
    }
    index.versions = kept;
    await writeIndex(projectRoot, index);
    try {
      await enforceBackupSizeLimit(projectRoot);
    } catch {
      /* */
    }
  } else {
    for (const v of index.versions) {
      if (!dropIds.has(v.id)) continue;
      freedBytes += v.bytes || 0;
    }
  }

  return {
    ok: true,
    dryRun,
    removed: dropIds.size,
    remaining: dryRun ? index.versions.length - dropIds.size : kept.length,
    freedBytes,
    sample: reasons.slice(0, 30),
    policy: { keepPerFile, maxTotal, maxAgeMs },
  };
}

/**
 * Restore a backup by id, or the latest for a path.
 * @returns {{ path, restoredFrom, bytes }}
 */
async function restoreBackup(projectRoot, { id = null, path: filePath = null } = {}) {
  if (!projectRoot) throw new Error("restore_backup requires an open project root");
  const index = await readIndex(projectRoot);
  const entry = findVersion(index, { id, path: filePath, projectRoot });
  if (!entry) {
    if (id) throw new Error(`Backup id not found: ${id}`);
    if (filePath) throw new Error(`No backup found for path: ${filePath}`);
    throw new Error("restore_backup requires 'id' or 'path'");
  }

  const buf = await readBackupBlob(projectRoot, entry);
  const targetAbs = toAbsolute(projectRoot, entry.path);

  let beforeStats = null;
  try {
    const current = await fs.promises.readFile(targetAbs, "utf8");
    beforeStats = fileDiff.quickChanged(buf.toString("utf8"), current);
  } catch {
    beforeStats = { changed: true, added: 0, removed: 0, equal: 0, missing: true };
  }

  try {
    await backupFileBeforeWrite(projectRoot, targetAbs, { reason: "pre-restore" });
  } catch {
    /* */
  }
  await fs.promises.mkdir(path.dirname(targetAbs), { recursive: true });
  await fs.promises.writeFile(targetAbs, buf);

  return {
    path: targetAbs,
    relativePath: entry.path,
    restoredFrom: entry.id,
    createdAt: entry.createdAt,
    createdAtIso: new Date(entry.createdAt).toISOString(),
    bytes: buf.length,
    statsBeforeRestore: beforeStats,
    message: `Restored ${entry.path} from snapshot ${entry.id} (full-file rollback, atomic write)`,
  };
}

/**
 * Resolve project root for a file path using context.rootPath, with fallback
 * walk-up looking for package.json / .git / .backup parent.
 */
function resolveProjectRoot(filePath, contextRoot) {
  if (contextRoot && typeof contextRoot === "string") {
    const root = path.resolve(contextRoot);
    const abs = path.resolve(filePath);
    const rel = path.relative(root, abs);
    if (rel && !rel.startsWith("..") && !path.isAbsolute(rel)) return root;
  }
  // Fallback: walk up
  let dir = path.dirname(path.resolve(filePath));
  for (let i = 0; i < 12; i += 1) {
    try {
      if (fs.existsSync(path.join(dir, "package.json")) || fs.existsSync(path.join(dir, ".git"))) {
        return dir;
      }
    } catch {
      /* */
    }
    const parent = path.dirname(dir);
    if (parent === dir) break;
    dir = parent;
  }
  return contextRoot ? path.resolve(contextRoot) : null;
}

